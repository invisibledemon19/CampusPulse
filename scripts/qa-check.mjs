import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const bannedVocab = [
  'seamless', 'seamlessly', 'unlock', 'empower', 'leverage', 'elevate',
  'supercharge', 'revolutionize', 'cutting-edge', 'game-changing', 'next-level',
  'journey', 'delve', 'tapestry', 'landscape', 'curated', 'tailored',
  'hassle-free', 'one-stop', 'all-in-one', "today's fast-paced",
  'take your career', 'we are passionate', 'dive in', 'level up'
];

const vocabRegex = new RegExp('\\b(' + bannedVocab.join('|') + ')\\b', 'i');
const stylingRegex = /rounded-full|rounded-3xl|gradient|violet|purple|indigo/i;
const dashRegex = /[\u2013\u2014]/;
const creditRegex = /lorem|made with|powered by|generated by|vite \+ react|antigravity|gemini|claude/i;
const emojiRegex = /[\u{1F300}-\u{1F64F}\u{1F680}-\u{1F6FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{1F900}-\u{1F9FF}\u{1F1E0}-\u{1F1FF}]/u;

let failed = false;

function scanDir(dir) {
  const entries = readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (['node_modules', '.git', 'dist'].includes(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      scanDir(full);
    } else if (/\.(jsx?|tsx?|html|css|json|md)$/.test(entry.name)) {
      // Don't scan docs folder for banned words (since docs define the banned words)
      if (full.startsWith('docs') || full === 'design.md' || full === 'architecture.md' || full === 'techstack.md') {
        continue;
      }
      const content = readFileSync(full, 'utf8');
      const lines = content.split('\n');

      lines.forEach((line, idx) => {
        const lineNum = idx + 1;
        if (dashRegex.test(line)) {
          console.error(`[FAIL] Em/En dash in ${full}:${lineNum}: ${line.trim()}`);
          failed = true;
        }
        if (stylingRegex.test(line)) {
          console.error(`[FAIL] Banned style in ${full}:${lineNum}: ${line.trim()}`);
          failed = true;
        }
        if (creditRegex.test(line)) {
          console.error(`[FAIL] Credit phrase in ${full}:${lineNum}: ${line.trim()}`);
          failed = true;
        }
        if (vocabRegex.test(line)) {
          console.error(`[FAIL] Banned vocabulary in ${full}:${lineNum}: ${line.trim()}`);
          failed = true;
        }
        if (emojiRegex.test(line)) {
          console.error(`[FAIL] Emoji in ${full}:${lineNum}: ${line.trim()}`);
          failed = true;
        }
      });
    }
  }
}

scanDir('src');
scanDir('public');
scanDir('scripts');
const readme = readFileSync('README.md', 'utf8');
if (dashRegex.test(readme) || stylingRegex.test(readme) || creditRegex.test(readme) || vocabRegex.test(readme) || emojiRegex.test(readme)) {
  console.error('[FAIL] Check failed on README.md');
  failed = true;
}
const indexHtml = readFileSync('index.html', 'utf8');
if (dashRegex.test(indexHtml) || stylingRegex.test(indexHtml) || creditRegex.test(indexHtml) || vocabRegex.test(indexHtml) || emojiRegex.test(indexHtml)) {
  console.error('[FAIL] Check failed on index.html');
  failed = true;
}

if (failed) {
  console.error('\nQA Check failed. Resolve the errors above.');
  process.exit(1);
} else {
  console.log('\nAll automated QA checks passed successfully:');
  console.log('- Zero em or en dashes');
  console.log('- Zero rounded-full, rounded-3xl, gradients, purple, violet, indigo');
  console.log('- Zero AI credit or generator tags');
  console.log('- Zero banned buzzwords');
  console.log('- Zero emojis in UI/code');
}
